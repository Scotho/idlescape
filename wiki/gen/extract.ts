export const REVISION = 274;

/** Throws unless `actual` (the commit really checked out in engine/content) matches `pinned` (scripts/upstream.lock). */
export function assertContentPinned(actual: string, pinned: string): void {
  if (actual !== pinned) throw new Error(`engine/content is at ${actual}, expected pinned ${pinned}; run scripts/setup.ps1`);
}

// The corpus is extracted from the PINNED upstream content only; content-custom/ is never read
// (wiki/gen/paths.ts sources engine/content alone). That is correct only while the overlay
// carries nothing this extractor would have parsed, so fail loudly the day it grows one rather
// than quietly shipping a wiki that describes a world nobody plays. See wiki/AUTHORING.md.
//
// The extensions are the ones wiki/gen/load.ts walks. Measured at HEAD, content-custom holds
// exactly two real files: pack/varp.pack, a packed id table this extractor never reads, and
// scripts/interface_bank/configs/banktab.varp, the bank-tab size varp SP8 added. The .varp is
// the one accepted exception: it is an interface config no wiki page describes.
const OVERLAY_PARSED = /\.(obj|npc|loc|inv|varp|param|dbtable|dbrow|rs2|constant|jm2)$/;
const OVERLAY_ACCEPTED = new Set(['scripts/interface_bank/configs/banktab.varp']);

/** Throws when content-custom/ carries a file this extractor would have parsed had it read the overlay. */
export function assertOverlayNotWikiVisible(overlayRoot = path.join(ROOT, 'content-custom')): void {
  if (!existsSync(overlayRoot)) return;
  const overlapping = (readdirSync(overlayRoot, { recursive: true }) as string[])
    .map(rel => rel.replace(/\\/g, '/'))
    .filter(rel => OVERLAY_PARSED.test(rel) && !OVERLAY_ACCEPTED.has(rel));
  if (overlapping.length > 0) {
    throw new Error(`content-custom/ now carries ${overlapping.length} file(s) this extractor parses (${overlapping.slice(0, 5).join(', ')}), but wiki/gen/paths.ts reads engine/content only, so the corpus would describe a world nobody plays. Teach paths.ts about the overlay, or add the file to OVERLAY_ACCEPTED in wiki/gen/extract.ts with the reason it is not wiki-visible.`);
  }
}

export function runExtract(contentDir = CONTENT, outRoot = DATA, rev = REVISION): Manifest {
  // engine/content tracks a moving upstream branch (see scripts/upstream.lock), so guard against
  // extracting from a checkout that has drifted past (or behind) the sha this revision is pinned to.
  const actualContentSha = contentHeadSha(contentDir);
  const { contentSha: pinnedContentSha, engineSha } = upstreamShas();
  assertContentPinned(actualContentSha, pinnedContentSha);
  assertOverlayNotWikiVisible();
  const c = loadContent(contentDir);
  const objPack = loadPackIds(contentDir, 'obj'), npcPack = loadPackIds(contentDir, 'npc'), locPack = loadPackIds(contentDir, 'loc'), invPack = loadPackIds(contentDir, 'inv');
  // category.pack is generated by the engine's packer, not tracked upstream, so a fresh clone (the
  // server image's wiki stage) has none; the only reader, drops.ts, resolves `_category_<id>` drop
  // subjects through it and reports them as unmatched when it is absent.
  const categoryPack = loadPackIdsIfPresent(contentDir, 'category');
  if (!categoryPack) console.warn('[wiki] pack/category.pack is absent (a clone without generated packs); drop subjects named by category id will be unmatched');
  const items = extractItems({ objTexts: c.obj, objPack, paramDefaults: loadParamDefaults(c.param.map(p => p.text)) });
  const npcs = extractNpcs({ npcTexts: c.npc, npcPack });
  const locs = extractLocs({ locTexts: c.loc, locPack });
  const areasApi = extractAreas({ labelsText: c.labels, free2playText: c.free2play, multiwayText: c.multiway });
  const spawns = extractSpawns({ jm2Files: c.jm2, npcPack, objPack, locPack, areas: areasApi });
  const blocks = c.rs2.flatMap(f => parseRs2(f.text, f.file));
  const shops = extractShops({ invTexts: c.inv, invPack, npcTexts: c.npc, npcPack, rs2Blocks: blocks, npcSpawns: spawns.filter(s => s.kind === 'npc') });
  const tables = parseDbTables(c.dbtable);
  const rows = parseDbRows(c.dbrow, tables);
  const skills = extractSkills({ statEnumText: c.statEnum, unlocksEnumText: c.unlocksEnum });
  const methods = extractMethods({ rows, tables });
  const { drops, unmatchedCategories } = extractDrops({ rs2Blocks: blocks, npcs, rows, tables, categoryPack });
  // NPC configs carry no members flag: an NPC is members-only when every one of its spawns sits in
  // a members zone. Items keep the config flag. Quests inherit the rule through their start NPC.
  const npcSpawns = new Map<string, typeof spawns>();
  for (const s of spawns) if (s.kind === 'npc') (npcSpawns.get(s.key) ?? npcSpawns.set(s.key, []).get(s.key)!).push(s);
  for (const n of npcs) { const sp = npcSpawns.get(n.key) ?? []; n.members = sp.length > 0 && sp.every(s => !areasApi.isFree(s.coord)); }
  const questFolders = [...new Set(c.rs2.concat(c.varp).map(f => /scripts\/quests\/(quest_[a-z0-9_]+)\//.exec(f.file)?.[1]).filter((x): x is string => !!x))]
    .map(folder => ({ folder, files: c.rs2.concat(c.varp).filter(f => f.file.includes(`/quests/${folder}/`)) }));
  const questNames = new Map(Object.entries(QUEST_NAMES).filter((e): e is [string, string] => e[1] !== null));
  const quests = extractQuests({ questFolders, allBlocks: blocks, constants: parseConstants(c.constants), questNames, npcKeys: new Set(npcPack.byKey.keys()), npcSpawns, isFree: areasApi.isFree });
  const membersUnknown = quests.filter(q => !q.startNpcKey || (npcSpawns.get(q.startNpcKey) ?? []).length === 0);

  // spawns.json is committed and stays small: npc + obj placements only. Loc placements dwarf everything else
  // (hundreds of thousands of wall/floor decorations) and are worth regenerating locally rather than committing,
  // so they go to a gitignored loc-spawns.json written without indentation.
  const entitySpawns = spawns.filter(s => s.kind !== 'loc');
  const locSpawns = spawns.filter(s => s.kind === 'loc');

  const manifest: Manifest = { revision: rev, contentSha: actualContentSha, engineSha, generatedAt: new Date().toISOString(),
    counts: { items: items.length, npcs: npcs.length, locs: locs.length, areas: areasApi.areas.length, spawns: spawns.length, entitySpawns: entitySpawns.length, locSpawns: locSpawns.length, shops: shops.length, skills: skills.length, methods: methods.length, drops: drops.length, quests: quests.length } };
  const out = path.join(outRoot, String(rev));
  mkdirSync(out, { recursive: true });
  const write = (name: string, v: unknown) => writeFileSync(path.join(out, name), JSON.stringify(v, null, 1) + '\n');
  write('items.json', items); write('npcs.json', npcs); write('locs.json', locs); write('areas.json', areasApi.areas); write('spawns.json', entitySpawns);
  writeFileSync(path.join(out, 'loc-spawns.json'), JSON.stringify(locSpawns));
  write('shops.json', shops); write('skills.json', skills); write('methods.json', methods); write('drops.json', drops); write('quests.json', quests); write('manifest.json', manifest);
  writeFileSync(path.join(out, 'gaps.md'), gapsReport({ quests, npcs, drops, items, unmatchedCategories, membersUnknown }));
  return manifest;
}

export function readData(rev = REVISION, root = DATA, regenerate: (rev: number, root: string) => void = (r, d) => { runExtract(CONTENT, d, r); }): ExtractedData {
  const dir = path.join(root, String(rev));
  const locSpawnsFile = path.join(dir, 'loc-spawns.json');
  if (!existsSync(locSpawnsFile)) regenerate(rev, root);
  const r = <T,>(n: string) => JSON.parse(readFileSync(path.join(dir, n), 'utf8')) as T;
  const spawns = [...r<ExtractedData['spawns']>('spawns.json'), ...r<ExtractedData['spawns']>('loc-spawns.json')];
  return { items: r('items.json'), npcs: r('npcs.json'), locs: r('locs.json'), areas: r('areas.json'), spawns, shops: r('shops.json'),
    skills: r('skills.json'), methods: r('methods.json'), drops: r('drops.json'), quests: r('quests.json'), manifest: r('manifest.json') };
}

const CHECKED_FILES = ['items.json', 'npcs.json', 'locs.json', 'areas.json', 'spawns.json',
  'shops.json', 'skills.json', 'methods.json', 'drops.json', 'quests.json', 'gaps.md'] as const;

const lf = (s: string): string => s.replace(/\r\n/g, '\n');

/** manifest.json minus generatedAt, which changes on every run and cannot be compared. */
export function stableManifest(text: string): string {
  const m = JSON.parse(text) as Record<string, unknown>;
  delete m.generatedAt;
  return JSON.stringify(m, null, 1);
}

/** Extracts to a temporary directory and reports every tracked file that differs. */
export function checkFull(rev = REVISION): string[] {
  const tmp = mkdtempSync(path.join(tmpdir(), 'wiki-check-'));
  try {
    runExtract(CONTENT, tmp, rev);
    const drift: string[] = [];
    for (const name of CHECKED_FILES) {
      const a = lf(readFileSync(path.join(DATA, String(rev), name), 'utf8'));
      const b = lf(readFileSync(path.join(tmp, String(rev), name), 'utf8'));
      if (a !== b) drift.push(name);
    }
    const ma = stableManifest(readFileSync(path.join(DATA, String(rev), 'manifest.json'), 'utf8'));
    const mb = stableManifest(readFileSync(path.join(tmp, String(rev), 'manifest.json'), 'utf8'));
    if (ma !== mb) drift.push('manifest.json');
    return drift;
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  if (process.argv.includes('--check-full')) {
    // Not cheap: a full re-extract parses every .jm2 map and produces over 800,000 loc placements.
    // loc-spawns.json is skipped because it is gitignored and is the reason this is slow.
    const drift = checkFull();
    if (drift.length > 0) {
      console.error(`[wiki] data drift in ${drift.join(', ')}; run: bun run --cwd wiki extract`);
      process.exit(1);
    }
    console.log('[wiki] tracked data matches a fresh extract');
  } else {
    const m = runExtract();
    console.log(`[wiki] extracted rev ${m.revision} @ ${m.contentSha.slice(0, 8)}:`, m.counts);
  }
}
