/** The module text `steps.ts` is written from. Newlines are LF; the caller owns line endings. */
export function renderStepsModule(steps: readonly string[]): string {
  const body = steps.map(step => `  '${step.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`).join('\n');
  return `${HEADER}\n${body}\n];\n`;
}
