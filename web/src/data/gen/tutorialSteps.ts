// The tutorial's on-screen step titles, read out of the content's chatbox script. `%tutorial` is
// a server-only varp, so the title the chatbox shows is the only step signal a client can see,
// which is why the Tutorial Island script keys on it and why this list is generated rather than
// typed out: a content bump that renames a step has to fail a test, not a live run.
//
// Pure half (plan ruling R2): `scripts/gen/tutorial-steps.ts` does the file IO.

/**
 * Every live `~tutorialstep("<title>", ...)` call in the file, in source order, empties included.
 *
 * A commented-out call is skipped. The content keeps one beside the call that replaced it (the
 * "Interacting with scenery" pair in `tut_chatbox_steps.rs2`, under a `// todo:` note), and
 * counting it made the generated list describe the file's text rather than the tutorial.
 */
export function extractTutorialSteps(source: string): string[] {
  const out: string[] = [];
  const re = /~tutorialstep\("((?:[^"\\]|\\.)*)"/g;
  for (let m = re.exec(source); m !== null; m = re.exec(source)) {
    if (isCommented(source, m.index)) continue;
    out.push(unescapeRs2(m[1]));
  }
  return out;
}

/** True when a line comment opens before `at` on the same line, which comments the call out. */
function isCommented(source: string, at: number): boolean {
  return source.slice(source.lastIndexOf('\n', at) + 1, at).includes('//');
}

/** RuneScript string escapes we can meet inside a title. Anything else is already literal. */
function unescapeRs2(raw: string): string {
  return raw.replace(/\\(["\\])/g, '$1');
}

