import { describe, expect, test } from 'vitest';
import { extractTutorialSteps, renderStepsModule } from './tutorialSteps';

/** Runs the emitted array literal as JavaScript, which is what a bundler will do with it. */
function evalArrayLiteral(module: string): unknown {
  const literal = module.slice(module.indexOf('['), module.lastIndexOf(']') + 1);
  return new Function(`return ${literal};`)();
}

describe('extractTutorialSteps', () => {
  test('keeps the calls in source order, empty titles included', () => {
    const source = [
      '[proc,tut_steps]',
      '~tutorialstep("Getting started", "Welcome.");',
      '~tutorialstep("", "Click the flashing spanner.");',
      '~tutorialstep("Player controls", "These are your controls.");'
    ].join('\n');
    expect(extractTutorialSteps(source)).toEqual(['Getting started', '', 'Player controls']);
  });

  test('reads an apostrophe as an ordinary character', () => {
    expect(extractTutorialSteps('~tutorialstep("It\'s copper.", "x");')).toEqual(["It's copper."]);
  });

  test('reads an escaped quote inside a title rather than stopping at it', () => {
    expect(extractTutorialSteps('~tutorialstep("say \\"hi\\" now", "x");')).toEqual(['say "hi" now']);
  });

  test('ignores a call to something else that happens to take a string', () => {
    const source = '~mesbox("Not a step");\n~tutorialstep("Mining.", "x");';
    expect(extractTutorialSteps(source)).toEqual(['Mining.']);
  });

  test('skips a call the content has commented out, which is not a step the tutorial calls', () => {
    // This is the shape in the pinned clone: a dead call kept beside the one that replaced it.
    const source = [
      '// todo: line breaks are forcing an additional page',
      '// ~tutorialstep("Interacting with scenery", "the long wording");',
      '~tutorialstep("Interacting with scenery", "the short wording");'
    ].join('\n');
    expect(extractTutorialSteps(source)).toEqual(['Interacting with scenery']);
  });

  test('skips a call commented out after live code on the same line, and keeps the live one', () => {
    const source = '~tutorialstep("Mining.", "x"); // ~tutorialstep("Smelting.", "x");';
    expect(extractTutorialSteps(source)).toEqual(['Mining.']);
  });

  test('a comment on the line above does not silence the call below it', () => {
    const source = '// the next step is live\n~tutorialstep("Prospecting", "x");';
    expect(extractTutorialSteps(source)).toEqual(['Prospecting']);
  });

  test('answers with nothing for a file that calls no steps', () => {
    expect(extractTutorialSteps('[proc,nothing]\nreturn;')).toEqual([]);
  });
});

describe('renderStepsModule', () => {
  test('quotes an apostrophe so the emitted module parses', () => {
    const text = renderStepsModule(["It's copper.", '']);
    expect(text).toContain("  'It\\'s copper.',");
    expect(text).toContain("  '',");
    // The emitted text has to be a module a bundler can read, and quoting is exactly where that
    // breaks. Evaluating the array literal is the cheapest proof that it did not.
    expect(evalArrayLiteral(text)).toEqual(["It's copper.", '']);
  });

  test('escapes a backslash before it can escape the closing quote', () => {
    expect(renderStepsModule(['a\\'])).toContain("  'a\\\\',");
    expect(evalArrayLiteral(renderStepsModule(['a\\', 'b']))).toEqual(['a\\', 'b']);
  });

  test('names the generator and the content file it read, so the file is not edited by hand', () => {
    const text = renderStepsModule([]);
    expect(text).toContain('GENERATED by scripts/gen/tutorial-steps.ts');
    expect(text).toContain('tut_chatbox_steps.rs2');
    expect(text).toContain('export const TUTORIAL_STEPS: readonly string[] = [');
  });

  test('ends with a newline and uses LF alone, so the check gate does not depend on the checkout', () => {
    const text = renderStepsModule(['Mining.']);
    expect(text.endsWith('];\n')).toBe(true);
    expect(text).not.toContain('\r');
  });
});
